//! Shared wire types for generated typed extension interfaces.

use std::sync::Arc;

use serde::{Deserialize, Serialize};

/// Recoverable extension/RPC failure.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, thiserror::Error)]
#[error("{message}")]
pub struct ExtensionError {
    /// Human-readable failure reason.
    pub message: String,
}

impl ExtensionError {
    /// Creates an error from a message.
    #[must_use]
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl From<String> for ExtensionError {
    fn from(message: String) -> Self {
        Self::new(message)
    }
}

impl From<&str> for ExtensionError {
    fn from(message: &str) -> Self {
        Self::new(message)
    }
}

/// Stable target for a generated implementation handle.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RemoteTarget {
    /// Stable implementation id.
    pub implementation_id: String,
    /// Registry generation captured by the handle.
    pub generation: u64,
}

impl RemoteTarget {
    /// Creates a remote target.
    #[must_use]
    pub fn new(implementation_id: impl Into<String>, generation: u64) -> Self {
        Self {
            implementation_id: implementation_id.into(),
            generation,
        }
    }
}

/// Transport used by generated handles to invoke an implementation.
pub trait RpcTransport: Send + Sync {
    /// Invokes one interface method with a postcard payload.
    fn invoke(
        &self,
        target: &RemoteTarget,
        context: &crate::ExtensionContext<'_>,
        interface_id: &'static str,
        interface_version: u32,
        method: &'static str,
        payload: &[u8],
    ) -> Result<Vec<u8>, ExtensionError>;
}

/// Convenience alias used by generated handles.
pub type SharedRpcTransport = Arc<dyn RpcTransport>;

/// Guest-side registration hook generated by `#[notwig_ext_trait]`.
///
/// The instance is moved into the guest registry and never leaves it.
pub trait ExtensionInstance<I: ?Sized> {
    /// Registers this instance inside the guest runtime.
    fn register_instance(self, extension: &mut crate::Extension, point_id: &'static str);
}

/// Erased guest-side typed interface dispatcher.
pub type InterfaceDispatch = Box<
    dyn Fn(&crate::ExtensionContext<'_>, &str, &[u8]) -> Result<Vec<u8>, ExtensionError>
        + Send
        + Sync,
>;

/// One registered typed interface inside a guest extension.
pub struct RegisteredInterface {
    /// Stable interface id.
    pub interface_id: &'static str,
    /// Interface major version.
    pub interface_version: u32,
    /// Stable implementation id inside this guest.
    pub implementation_id: String,
    /// Erased dispatcher owned by the guest.
    pub dispatch: InterfaceDispatch,
}

impl std::fmt::Debug for RegisteredInterface {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RegisteredInterface")
            .field("interface_id", &self.interface_id)
            .field("interface_version", &self.interface_version)
            .field("implementation_id", &self.implementation_id)
            .finish_non_exhaustive()
    }
}
