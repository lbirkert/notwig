//! Shared wire types for generated typed extension interfaces.

use std::sync::Arc;

use serde::{Deserialize, Serialize};

/// Recoverable extension/RPC failure.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, thiserror::Error)]
#[error("{message}")]
pub struct ExtensionError {
    /// Human-readable failure reason.
    pub message: String,
}

impl ExtensionError {
    /// Creates an error from a message.
    #[must_use]
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl From<String> for ExtensionError {
    fn from(message: String) -> Self {
        Self::new(message)
    }
}

impl From<&str> for ExtensionError {
    fn from(message: &str) -> Self {
        Self::new(message)
    }
}

/// Stable target for a generated implementation handle.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RemoteTarget {
    /// Stable implementation id.
    pub implementation_id: String,
    /// Registry generation captured by the handle.
    pub generation: u64,
}

impl RemoteTarget {
    /// Creates a remote target.
    #[must_use]
    pub fn new(implementation_id: impl Into<String>, generation: u64) -> Self {
        Self {
            implementation_id: implementation_id.into(),
            generation,
        }
    }
}

/// Transport used by generated handles to invoke an implementation.
pub trait RpcTransport: Send + Sync {
    /// Invokes one interface method with a postcard payload.
    fn invoke(
        &self,
        target: &RemoteTarget,
        context: &crate::ExtensionContext<'_>,
        interface_id: &'static str,
        interface_version: u32,
        method: &'static str,
        payload: &[u8],
    ) -> Result<Vec<u8>, ExtensionError>;
}

/// Convenience alias used by generated handles.
pub type SharedRpcTransport = Arc<dyn RpcTransport>;

/// Guest-side callable interface object generated by `#[notwig_ext_trait]`.
///
/// The concrete extension instance implements this trait and stays inside the
/// guest runtime. The scheduler dispatches by object/index and passes raw
/// request bytes.
pub trait ExtensionCall: Send + Sync {
    /// Stable interface id.
    fn interface_id(&self) -> &'static str;

    /// Interface major version.
    fn interface_version(&self) -> u32;

    /// Processes one postcard-encoded method request.
    fn process(
        &mut self,
        context: &crate::ExtensionContext<'_>,
        method: &str,
        payload: &[u8],
    ) -> Result<Vec<u8>, ExtensionError>;
}

/// Associates an extension interface with its generated handle type.
///
/// Implemented for `dyn Trait` by `#[notwig_ext_trait]`.
pub trait ExtensionTrait {
    /// Generated handle proxy for this interface.
    type Handle;

    /// Stable interface id.
    const INTERFACE_ID: &'static str;
    /// Interface major version.
    const INTERFACE_VERSION: u32;

    /// Creates a handle that schedules calls through `transport`.
    fn create_handle(transport: SharedRpcTransport, target: RemoteTarget) -> Self::Handle;
}
