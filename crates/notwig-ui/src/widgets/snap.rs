use notwig_core::TimeMus;

/// Note-value relative to a whole note (e.g. `1/16` is a sixteenth note).
///
/// `TimeMus` counts quarter notes, so a whole note is four beats.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct SnapLevel {
    numerator: u32,
    denominator: u32,
}

impl SnapLevel {
    #[must_use]
    pub const fn new(numerator: u32, denominator: u32) -> Self {
        Self {
            numerator,
            denominator,
        }
    }

    /// Length in beats (quarter notes).
    #[must_use]
    pub fn beats(self) -> f64 {
        4.0 * f64::from(self.numerator) / f64::from(self.denominator)
    }

    #[must_use]
    pub fn step(self) -> TimeMus {
        beats_to_time(self.beats())
    }

    #[must_use]
    pub fn label(self) -> String {
        format!("{}/{}", self.numerator, self.denominator)
    }

    #[must_use]
    pub fn from_beats(beats: f64) -> Option<Self> {
        let step = beats_to_time(beats);
        SNAP_LEVELS
            .iter()
            .copied()
            .find(|level| level.step() == step)
    }
}

/// Selectable snap levels, ordered from the coarsest to the finest.
pub const SNAP_LEVELS: &[SnapLevel] = &[
    SnapLevel::new(2, 1),
    SnapLevel::new(1, 1),
    SnapLevel::new(1, 2),
    SnapLevel::new(1, 4),
    SnapLevel::new(1, 8),
    SnapLevel::new(1, 16),
    SnapLevel::new(1, 32),
    SnapLevel::new(1, 64),
    SnapLevel::new(1, 128),
    SnapLevel::new(1, 256),
    SnapLevel::new(1, 512),
    SnapLevel::new(1, 1024),
    SnapLevel::new(1, 2048),
    SnapLevel::new(1, 4096),
    SnapLevel::new(1, 8192),
    SnapLevel::new(1, 16384),
    SnapLevel::new(1, 32768),
    SnapLevel::new(1, 65536),
];

/// Minimum spacing, in pixels, for an adaptive grid line.
///
/// This is deliberately larger than the old 12 px threshold so adaptive mode
/// shows fewer, larger subdivisions at the same zoom level.
const ADAPTIVE_MIN_PIXELS: f32 = 40.0;

/// Upper bound for the bar multiples generated by adaptive snapping.
///
/// Powers of two are generated until the spacing threshold is met, so this
/// bound only matters for very narrow bars at very low zoom.
const MAX_BAR_MULTIPLIER: i64 = 1024;

/// Global snap configuration shared by every timeline editor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SnapSettings {
    pub enabled: bool,
    pub adaptive: bool,
    pub level: SnapLevel,
}

impl Default for SnapSettings {
    fn default() -> Self {
        Self {
            enabled: true,
            adaptive: true,
            level: SnapLevel::new(1, 16),
        }
    }
}

impl SnapSettings {
    /// The one effective step used for painting the grid, snapping gestures,
    /// and labels.
    #[must_use]
    pub fn step(self, pixels_per_beat: f32, bar_length: TimeMus) -> TimeMus {
        if self.adaptive {
            adaptive_step(pixels_per_beat, bar_length)
        } else {
            self.level.step()
        }
    }

    #[must_use]
    pub fn snap(
        self,
        time: TimeMus,
        pixels_per_beat: f32,
        bar_length: TimeMus,
        bypass: bool,
    ) -> TimeMus {
        if !self.enabled || bypass {
            return time;
        }
        snap_time(time, self.step(pixels_per_beat, bar_length), false)
    }

    /// Returns `true` when a gesture must not snap.
    ///
    /// Shift is the universal bypass; Alt remains supported because the clip
    /// and audio editors already document it. Turning snap off disables it for
    /// every editor at once.
    #[must_use]
    pub fn bypassed(self, modifiers: egui::Modifiers) -> bool {
        !self.enabled || modifiers.shift || modifiers.alt
    }
}

/// Chooses the finest adaptive division that still leaves at least
/// [`ADAPTIVE_MIN_PIXELS`] between lines and is commensurate with one bar.
#[must_use]
pub fn adaptive_step(pixels_per_beat: f32, bar_length: TimeMus) -> TimeMus {
    let ppb = pixels_per_beat.max(0.0);
    let bar = positive_bar(bar_length);
    if ppb <= 0.0 {
        return bar;
    }

    // Only note values that divide the bar, or are an integer multiple of it,
    // produce lines that stay aligned with bar boundaries.
    let mut candidates: Vec<TimeMus> = SNAP_LEVELS
        .iter()
        .copied()
        .map(SnapLevel::step)
        .filter(|step| commensurate(*step, bar))
        .collect();

    let min_beats = f64::from(ADAPTIVE_MIN_PIXELS) / f64::from(ppb);
    let mut multiplier = 1_i64;
    loop {
        let step = multiply_time(bar, multiplier);
        candidates.push(step);
        if step.as_f64() >= min_beats || multiplier >= MAX_BAR_MULTIPLIER {
            break;
        }
        multiplier = (multiplier * 2).min(MAX_BAR_MULTIPLIER);
    }

    candidates.sort_unstable();
    candidates.dedup();
    let fallback = *candidates
        .last()
        .expect("snap candidates are never empty after adding bar multiples");
    candidates
        .into_iter()
        .find(|step| step.as_f64() as f32 * ppb >= ADAPTIVE_MIN_PIXELS)
        .unwrap_or(fallback)
}

#[must_use]
pub fn snap_step(pixels_per_beat: f32, bar_length: TimeMus) -> TimeMus {
    adaptive_step(pixels_per_beat, bar_length)
}

#[must_use]
pub fn snap_time(time: TimeMus, step: TimeMus, bypass: bool) -> TimeMus {
    if bypass || step.is_zero() {
        return time;
    }
    let beats = time.as_f64();
    let step_beats = step.as_f64();
    let snapped = (beats / step_beats).round() * step_beats;
    beats_to_time(snapped)
}

#[must_use]
pub fn snap_step_label(step: TimeMus, bar_length: TimeMus) -> String {
    if let Some(level) = SnapLevel::from_beats(step.as_f64()) {
        return level.label();
    }
    let bar = positive_bar(bar_length);
    if let Some(bars) = integer_ratio(step, bar) {
        if bars == 1 {
            "1 bar".into()
        } else {
            format!("{bars} bars")
        }
    } else {
        format!("{:.3} beats", step.as_f64())
    }
}

fn positive_bar(bar_length: TimeMus) -> TimeMus {
    if bar_length > TimeMus::zero() {
        bar_length
    } else {
        TimeMus::new(4, 1)
    }
}

fn multiply_time(time: TimeMus, multiplier: i64) -> TimeMus {
    TimeMus::new(time.num().saturating_mul(multiplier), time.den())
}

fn commensurate(step: TimeMus, bar: TimeMus) -> bool {
    integer_ratio(bar, step).is_some() || integer_ratio(step, bar).is_some()
}

/// Returns `a / b` when it is an exact integer.
fn integer_ratio(a: TimeMus, b: TimeMus) -> Option<i64> {
    if b.num() == 0 {
        return None;
    }
    let numerator = i128::from(a.num()) * i128::from(b.den());
    let denominator = i128::from(a.den()) * i128::from(b.num());
    if denominator == 0 || numerator % denominator != 0 {
        return None;
    }
    i64::try_from(numerator / denominator).ok()
}

fn beats_to_time(beats: f64) -> TimeMus {
    TimeMus::new((beats * 1_000_000.0).round() as i64, 1_000_000)
}
